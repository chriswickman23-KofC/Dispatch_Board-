using System.ComponentModel.DataAnnotations;
using Dispatch.Shared;

namespace Dispatch.Web.Data;

public class Zone
{
    public int Id { get; set; }
    [MaxLength(50)] public string Name { get; set; } = "";
}

public class Client
{
    public int Id { get; set; }
    [MaxLength(200)] public string Name { get; set; } = "";
    public string? ContactName { get; set; }
    public string? ContactPhone { get; set; }
    public string? ContactEmail { get; set; }
    public string? DefaultPickupAddress { get; set; }
    public double? DefaultPickupLat { get; set; }
    public double? DefaultPickupLng { get; set; }
    public string? CsvMapping { get; set; }   // JSON: remembered CSV column layout
    public string? Notes { get; set; }
    public bool Active { get; set; } = true;
    public bool SendCustomerTexts { get; set; } = true;   // some clients notify their own customers
}

public class Driver
{
    public int Id { get; set; }
    public string? UserId { get; set; }
    public ApplicationUser? User { get; set; }
    [MaxLength(100)] public string Name { get; set; } = "";
    public string? Phone { get; set; }
    public int? ZoneId { get; set; }
    public Zone? Zone { get; set; }
    public DriverStatus Status { get; set; } = DriverStatus.Offline;
    public double? CurrentLat { get; set; }
    public double? CurrentLng { get; set; }
    public DateTimeOffset? LastPingAt { get; set; }
    public bool Active { get; set; } = true;
}

public class DriverRoute
{
    public int Id { get; set; }
    public int DriverId { get; set; }
    public Driver Driver { get; set; } = null!;
    public DateOnly RouteDate { get; set; }
}

public class Job
{
    public int Id { get; set; }
    public string Ref { get; set; } = null!;          // "J-1000", generated by the database
    public int? ClientId { get; set; }
    public Client? Client { get; set; }
    public string? RecipientName { get; set; }
    public string? RecipientPhone { get; set; }
    public JobType Type { get; set; }
    public JobStatus Status { get; set; } = JobStatus.Unassigned;
    public JobSource Source { get; set; } = JobSource.Manual;
    public string? ExternalId { get; set; }            // client order number
    public int? ZoneId { get; set; }
    public Zone? Zone { get; set; }
    public DateOnly? ScheduledDate { get; set; }
    public DateTimeOffset? WindowStart { get; set; }
    public DateTimeOffset? WindowEnd { get; set; }
    public int? DriverId { get; set; }
    public Driver? Driver { get; set; }
    public int? RouteId { get; set; }
    public DriverRoute? Route { get; set; }
    public string? Notes { get; set; }
    public string? CreatedById { get; set; }
    public DateTimeOffset CreatedAt { get; set; } = DateTimeOffset.UtcNow;
    public DateTimeOffset UpdatedAt { get; set; } = DateTimeOffset.UtcNow;
    public DateTimeOffset? ReviewedAt { get; set; }
    public string? ReviewedById { get; set; }
    public string? TrackingToken { get; set; }

    [Timestamp] public uint Version { get; set; }      // maps to Postgres xmin for conflict detection

    public List<Stop> Stops { get; set; } = new();
    public List<JobEvent> Events { get; set; } = new();
}

public class Stop
{
    public int Id { get; set; }
    public int JobId { get; set; }
    public Job Job { get; set; } = null!;
    public StopKind Kind { get; set; }
    public string Address { get; set; } = "";
    public double Lat { get; set; }
    public double Lng { get; set; }
    public int? RouteId { get; set; }
    public int? Sequence { get; set; }
    public StopStatus Status { get; set; } = StopStatus.Pending;
    public DateTimeOffset? ArrivedAt { get; set; }
    public DateTimeOffset? CompletedAt { get; set; }
    public string? FailureReason { get; set; }
    public DateTimeOffset? EstimatedArrival { get; set; }
    public List<Proof> Proofs { get; set; } = new();
}

public class Proof
{
    public int Id { get; set; }
    public int StopId { get; set; }
    public string? PhotoPath { get; set; }
    public string? SignaturePath { get; set; }
    public string? RecipientName { get; set; }
    public double? Lat { get; set; }
    public double? Lng { get; set; }
    public DateTimeOffset CapturedAt { get; set; } = DateTimeOffset.UtcNow;
}

public class DriverLocation
{
    public long Id { get; set; }
    public int DriverId { get; set; }
    public double Lat { get; set; }
    public double Lng { get; set; }
    public float? AccuracyM { get; set; }
    public DateTimeOffset RecordedAt { get; set; }
}

public class JobEvent
{
    public long Id { get; set; }
    public int JobId { get; set; }
    public string? ActorId { get; set; }
    public string ActorName { get; set; } = "";
    [MaxLength(50)] public string Action { get; set; } = "";   // assigned, stop_failed, note…
    public string Description { get; set; } = "";
    public DateTimeOffset CreatedAt { get; set; } = DateTimeOffset.UtcNow;
}

public enum NotificationStatus { Pending, Sent, Failed }

public class CustomerNotification
{
    public long Id { get; set; }
    public int JobId { get; set; }
    [MaxLength(60)] public string Kind { get; set; } = "";   // e.g. "on_the_way:2026-10-26"
    [MaxLength(20)] public string ToPhone { get; set; } = "";
    public string Body { get; set; } = "";
    public NotificationStatus Status { get; set; } = NotificationStatus.Pending;
    public string? Error { get; set; }
    public DateTimeOffset CreatedAt { get; set; } = DateTimeOffset.UtcNow;
    public DateTimeOffset? SentAt { get; set; }
}

public enum IntegrationKind { Api, Shopify }
public enum OrderFilter { AllWithShippingAddress, ShippingMethodContains, HasTag }

public class ClientIntegration
{
    public int Id { get; set; }
    public Guid PublicId { get; set; } = Guid.NewGuid();   // used in webhook URLs instead of the guessable Id
    public int ClientId { get; set; }
    public Client Client { get; set; } = null!;
    public IntegrationKind Kind { get; set; }
    public bool Active { get; set; } = true;

    [MaxLength(64)] public string? ApiKeyHash { get; set; }
    [MaxLength(12)] public string? ApiKeyPrefix { get; set; }

    [MaxLength(200)] public string? ShopDomain { get; set; }
    public string? ProtectedSecret { get; set; }   // webhook signing secret, encrypted at rest

    public OrderFilter Filter { get; set; } = OrderFilter.AllWithShippingAddress;
    [MaxLength(100)] public string? FilterValue { get; set; }
    public TimeOnly SameDayCutoff { get; set; } = new(14, 0);
    public TimeOnly? WindowStart { get; set; }
    public TimeOnly? WindowEnd { get; set; }
    public int? ZoneId { get; set; }

    public DateTimeOffset CreatedAt { get; set; } = DateTimeOffset.UtcNow;
    public DateTimeOffset? LastOrderAt { get; set; }
    public string? LastError { get; set; }
}

public class IntakeLog
{
    public long Id { get; set; }
    public int IntegrationId { get; set; }
    [MaxLength(100)] public string ExternalId { get; set; } = "";
    [MaxLength(20)] public string Outcome { get; set; } = "";
    public string? Detail { get; set; }
    public int? JobId { get; set; }
    public DateTimeOffset ReceivedAt { get; set; } = DateTimeOffset.UtcNow;
}

public class ClosedDay
{
    public int Id { get; set; }
    public DateOnly Date { get; set; }
    [MaxLength(80)] public string Name { get; set; } = "";
    [MaxLength(100)] public string? CreatedBy { get; set; }
    public DateTimeOffset CreatedAt { get; set; } = DateTimeOffset.UtcNow;
}
